"""4) Сравнение Recall@10: общая модель минус правило.

Порог прироста 0,10 записан до прогона. Подтверждена, если
прирост не меньше порога. Модели этот файл не учит: пишет
зафиксированную таблицу вердикта.

200 семей: 0,494 против 0,631, прирост +0,137, 2 807 походов.
500 семей, семя 43: 0,496 против 0,648, прирост +0,152,
6 646 походов. Ta Feng без остатка: прирост +0,07, порог не взят.
"""

from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
OUT = HERE.parent / "результаты" / "recall10.csv"
GAIN = 0.10
VERDICT = (
    {
        "база": "200 семей",
        "походов": 2807,
        "обычно_берут": 0.494,
        "модель": 0.631,
        "прирост": 0.137,
        "порог": GAIN,
        "вердикт": "подтверждена",
    },
    {
        "база": "500 семей семя 43",
        "походов": 6646,
        "обычно_берут": 0.496,
        "модель": 0.648,
        "прирост": 0.152,
        "порог": GAIN,
        "вердикт": "подтверждена",
    },
    {
        "база": "Ta Feng чеки без остатка",
        "походов": 17062,
        "обычно_берут": "",
        "модель": "",
        "прирост": 0.07,
        "порог": GAIN,
        "вердикт": "не подтверждена",
    },
)


def compare(model_recall, rule_recall):
    """Вернуть прирост модели над правилом и вердикт.

    Прирост — ``model_recall`` минус ``rule_recall``.
    Вердикт «подтверждена», если прирост не меньше ``GAIN``.

    Args:
        model_recall: Средний Recall@10 общей модели по походам.
        rule_recall: Средний Recall@10 правила по тем же походам.

    Returns:
        tuple: ``(gain, verdict)``. ``gain`` — разность средних.
        ``verdict`` — строка «подтверждена» или
        «не подтверждена».

    Examples:
        >>> gain, verdict = compare(0.631, 0.494)
        >>> round(gain, 3), verdict
        (0.137, 'подтверждена')
    """
    gain = model_recall - rule_recall
    verdict = "подтверждена" if gain >= GAIN else "не подтверждена"
    return gain, verdict


def main():
    """Записать таблицу вердикта H2 в ``результаты/recall10.csv``.

    Строки — константа ``VERDICT``. Обучение не запускается.

    Notes:
        Каталог ``результаты`` создаётся при отсутствии.
        Файл перезаписывается.

    Examples:
        python 4_сравнение_recall.py
    """
    frame = pd.DataFrame(list(VERDICT))
    OUT.parent.mkdir(parents=True, exist_ok=True)
    frame.to_csv(OUT, index=False)
    for row in VERDICT:
        print(
            f"{row['база']}: правило {row['обычно_берут']}, "
            f"модель {row['модель']}, прирост {row['прирост']}, "
            f"порог {row['порог']}, {row['вердикт']}"
        )


if __name__ == "__main__":
    main()
